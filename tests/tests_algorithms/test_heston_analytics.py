"""Tests for HestonAnalytics: pricing, BS/IV helpers, JAX pricer, and calibration.

Calibration tests use small synthetic surfaces generated by the pricer itself so a
round-trip should recover the parameters. The NUTS test runs a tiny sampler -- it
checks plumbing (shapes/keys/return type), not posterior accuracy.
"""
import logging

import jax.numpy as jnp
import numpy as np
import pytest

from src.algorithms.heston import heston_analytics
from src.algorithms.heston.heston_analytics import HestonAnalytics
from src.algorithms.heston.heston_params import HestonParams

S_0 = 100.0
R = 0.02
TRUE = HestonParams(v_0=0.04, v_mean=0.04, a=1.5, eta=0.3, rho=-0.6)


def _surface() -> tuple[np.ndarray, np.ndarray]:
    """A small scattered strike/maturity grid flattened to parallel arrays."""
    ks = np.array([90.0, 95.0, 100.0, 105.0, 110.0])
    ts = np.array([0.25, 0.5, 1.0])
    k, t = np.meshgrid(ks, ts)
    return k.ravel(), t.ravel()


@pytest.fixture
def pricer() -> HestonAnalytics:
    return HestonAnalytics(TRUE)


