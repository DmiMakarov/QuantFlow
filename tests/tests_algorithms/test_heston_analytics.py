from src.algorithms.heston.heston_params import HestonParams

S_0 = 100.0
R = 0.02
TRUE = HestonParams(v_0=0.04, v_mean=0.04, a=1.5, eta=0.3, rho=-0.6)


def _surface() -> tuple[np.ndarray, np.ndarray]:
    """A small scattered strike/maturity grid flattened to parallel arrays."""
    ks = np.array([90.0, 95.0, 100.0, 105.0, 110.0])
    ts = np.array([0.25, 0.5, 1.0])
    k, t = np.meshgrid(ks, ts)
    return k.ravel(), t.ravel()


@pytest.fixture
def pricer() -> HestonModel:
    return HestonModel(TRUE)


