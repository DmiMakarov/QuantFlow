def test_bs_call_matches_known_value() -> None:
    # ATM, r=0, t=1, sigma=0.2 -> price = S0*(2*Phi(0.1)-1)
    price = HestonModel._bs_call(100.0, 100.0, 0.0, 1.0, 0.2)
    from scipy.stats import norm
    expected = 100.0 * (2 * norm.cdf(0.1) - 1)
    assert price == pytest.approx(expected, rel=1e-12)


def test_bs_vega_positive_and_peaks_atm() -> None:
    k = np.array([80.0, 100.0, 120.0])
    t = np.full(3, 1.0)
    vega = HestonModel._bs_vega(100.0, k, 0.0, t, np.full(3, 0.2))
    assert np.all(vega > 0)
    assert vega[1] == vega.max()  # ATM vega is largest


def test_implied_vol_roundtrip() -> None:
    sigma = 0.27
