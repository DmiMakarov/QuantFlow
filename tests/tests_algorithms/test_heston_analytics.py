# --------------------------------------------------------------------------- #
# optimize_params orchestration (mock the two stages -> fast)
# --------------------------------------------------------------------------- #
def test_optimize_params_runs_both_stages(monkeypatch: pytest.MonkeyPatch) -> None:
    cal = HestonAnalytics(TRUE)
    mse_out = HestonParams(v_0=0.05, v_mean=0.05, a=1.0, eta=0.2, rho=-0.4)
    nuts_out = HestonParams(v_0=0.03, v_mean=0.03, a=2.0, eta=0.25, rho=-0.7)
    calls = {}

    def fake_mse(*, init_params, k, s_0, r, t, call):  # noqa: ANN001, ANN003
        calls["mse_init"] = init_params
        return mse_out

    def fake_nuts(*, init_params, k, s_0, r, t, call):  # noqa: ANN001, ANN003
        calls["nuts_init"] = init_params
        return nuts_out

    monkeypatch.setattr(cal, "mse_optimizer", fake_mse)
    monkeypatch.setattr(cal, "nuts_optimizer", fake_nuts)

    k, t = _surface()
    cal.optimize_params(k=k, s_0=S_0, r=R, t=t, call=np.ones_like(k))
    assert calls["mse_init"] is TRUE              # seeded from self.params
    assert calls["nuts_init"] is mse_out          # NUTS warm-started from MSE
    assert cal.params is nuts_out                 # final params = NUTS result
