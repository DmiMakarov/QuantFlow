def test_gauss_legendre_nodes() -> None:
    nodes, weights = HestonAnalytics._gauss_legendre(200.0, 64)
    assert nodes.shape == (64,)
    assert weights.shape == (64,)
    assert float(nodes.min()) > 0.0
    assert float(nodes.max()) < 200.0
    assert float(weights.sum()) == pytest.approx(200.0, rel=1e-10)  # integrates 1


def test_call_jax_matches_numpy(pricer: HestonAnalytics) -> None:
    k, t = _surface()
    ref = pricer.call(k, S_0, R, t)
    nodes, weights = HestonAnalytics._gauss_legendre(200.0, 128)
    pv = jnp.asarray([TRUE.v_0, TRUE.v_mean, TRUE.a, TRUE.eta, TRUE.rho])
    jx = np.asarray(
        HestonAnalytics._call_jax(pv, jnp.asarray(k), S_0, R, jnp.asarray(t), nodes, weights),
    )
    np.testing.assert_allclose(jx, ref, rtol=1e-6)


