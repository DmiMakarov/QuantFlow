# Analytical pricer
# --------------------------------------------------------------------------- #
def test_call_is_positive_and_decreasing_in_strike(pricer: HestonAnalytics) -> None:
    k = np.array([80.0, 100.0, 120.0])
    t = np.array([1.0, 1.0, 1.0])
    prices = pricer.call(k, S_0, R, t)
    assert np.all(prices > 0)
    assert np.all(np.diff(prices) < 0)  # calls cheaper as strike rises


def test_call_above_intrinsic(pricer: HestonAnalytics) -> None:
    k = np.array([90.0])
    t = np.array([0.5])
    intrinsic = S_0 - k * np.exp(-R * t)
    assert pricer.call(k, S_0, R, t)[0] > intrinsic[0]


def test_call_with_explicit_params_differs(pricer: HestonAnalytics) -> None:
    # exercises the `params is not None` branch across cf/_pi1/_pi2/call
    k = np.array([100.0])
    t = np.array([1.0])
    other = HestonParams(v_0=0.09, v_mean=0.09, a=1.5, eta=0.3, rho=-0.6)
    base = pricer.call(k, S_0, R, t)[0]
    bumped = pricer.call(k, S_0, R, t, params=other)[0]
    assert bumped > base  # higher variance -> pricier call


def test_put_call_parity(pricer: HestonAnalytics) -> None:
    k = np.array([95.0, 105.0])
    t = np.array([0.5, 0.5])
    call = pricer.call(k, S_0, R, t)
    put = pricer.put(k, S_0, R, t)
    np.testing.assert_allclose(put, call - S_0 + k * np.exp(-R * t), rtol=1e-10)


