"""Tests for HestonModel: pricing, BS/IV helpers, JAX pricer, and calibration.

Calibration tests use small synthetic surfaces generated by the pricer itself so a
round-trip should recover the parameters. The NUTS test runs a tiny sampler -- it
checks plumbing (shapes/keys/return type), not posterior accuracy.
"""
