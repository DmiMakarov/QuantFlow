    assert "dropping" in caplog.text
    assert isinstance(post, HestonParams)
    assert set(cal.posterior) == {"v_0", "v_mean", "a", "eta", "rho", "sigma"}
    assert np.asarray(cal.posterior["v_0"]).shape == (4,)


