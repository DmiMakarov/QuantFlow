def test_default_quadrature_is_converged_at_short_maturities() -> None:
    """The inversion integral truncates at u_max, and the Heston CF decays like
    exp(-c*v*t*u^2) -- so the SHORT end is what strains it, not the long end. The legacy
    (200, 128) default carries a 0.63 absolute price error at T=0.017 on calibrated SPX
    params, which flows straight into the calibration objective and then masquerades as model
    error in any MC-vs-Fourier check. Pin the convergence, not the literal.
    """
    # a rough, Feller-violating slice, as real SPX calibrations produce
    rough = HestonParams(v_0=0.02, v_mean=0.12, a=0.92, eta=0.97, rho=-0.73)
    s_0 = 7500.0
    k = np.array([0.9, 1.0, 1.1]) * s_0

    gold = HestonModel(rough, HestonCalibrationConfig(quad=QuadConfig(u_max=3000, n_quad=2048)))
    default = HestonModel(rough)

    for ttm in (0.017, 0.14, 1.0):
        t = np.full_like(k, ttm)
        err = np.abs(default.call(k, s_0, R, t) - gold.call(k, s_0, R, t)).max()
        assert err < 1e-3, f"T={ttm}: default quadrature is off by {err:.3g}"


def test_custom_quad_flows_into_call() -> None:
    # A deliberately coarse grid changes the price -> proves call() reads config.
    k = np.array([100.0])
    t = np.array([1.0])
    fine = HestonModel(TRUE).call(k, S_0, R, t)[0]
    coarse = HestonModel(
        TRUE, HestonCalibrationConfig(quad=QuadConfig(n_quad=8)),
    ).call(k, S_0, R, t)[0]
    assert coarse != pytest.approx(fine, rel=1e-6)


def test_custom_mse_bounds_clip(pricer: HestonModel) -> None:
    # Cap `a` (3rd param) well below its true value -> fit must clip at the bound.
    k, t = _surface()
    call = pricer.call(k, S_0, R, t)
    bounds = (
        (1e-4, 1.0), (1e-4, 1.0), (1e-2, 0.5), (1e-2, 5.0), (-0.999, 0.999),
    )
    cfg = HestonCalibrationConfig(mse=MSEConfig(bounds=bounds))
    start = HestonParams(v_0=0.06, v_mean=0.06, a=0.4, eta=0.45, rho=-0.3)
    fitted = HestonModel(start, cfg).mse_optimizer(start, k, S_0, R, t, call)
    assert fitted.a <= 0.5 + 1e-9


def test_nuts_kwarg_overrides_config() -> None:
    # config asks for many samples; the per-call kwarg overrides it.
    k, t = _surface()
    call = HestonModel(TRUE).call(k, S_0, R, t)
    cfg = HestonCalibrationConfig(nuts=NUTSConfig(num_samples=999, num_warmup=4))
    cal = HestonModel(TRUE, cfg)
    cal.nuts_optimizer(TRUE, k, S_0, R, t, call, num_samples=4, n_quad=16)
    # kwarg num_samples=4 wins over cfg's 999; flattened over default 4 chains -> 16
    assert np.asarray(cal.posterior["v_0"]).shape == (NUTSConfig().num_chains * 4,)
