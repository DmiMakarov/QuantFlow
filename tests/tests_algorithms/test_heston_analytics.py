def test_mse_optimizer_recovers_params(pricer: HestonAnalytics) -> None:
    k, t = _surface()
    call = pricer.call(k, S_0, R, t)
    start = HestonParams(v_0=0.06, v_mean=0.06, a=2.5, eta=0.45, rho=-0.3)
    fitted = HestonAnalytics(start).mse_optimizer(start, k, S_0, R, t, call)
    for got, exp in zip(
        (fitted.v_0, fitted.v_mean, fitted.a, fitted.eta, fitted.rho),
        (TRUE.v_0, TRUE.v_mean, TRUE.a, TRUE.eta, TRUE.rho),
        strict=True,
    ):
        assert got == pytest.approx(exp, abs=1e-3)


def test_mse_optimizer_drops_invalid_quotes(
    pricer: HestonAnalytics, caplog: pytest.LogCaptureFixture,
) -> None:
    k, t = _surface()
    call = pricer.call(k, S_0, R, t)
    # append one arbitrage-violating quote (price above spot) -> dropped
    k = np.append(k, 100.0)
    t = np.append(t, 0.5)
    call = np.append(call, 2 * S_0)
    with caplog.at_level(logging.WARNING):
        fitted = HestonAnalytics(TRUE).mse_optimizer(TRUE, k, S_0, R, t, call)
    assert "Dropping" in caplog.text
    assert fitted.a == pytest.approx(TRUE.a, abs=1e-2)


def test_mse_optimizer_all_invalid_raises(pricer: HestonAnalytics) -> None:
    k = np.array([100.0, 100.0])
    t = np.array([0.5, 1.0])
    call = np.array([2 * S_0, 3 * S_0])  # both violate no-arb -> nothing to fit
    with pytest.raises(ValueError, match="No valid quotes"):
        HestonAnalytics(TRUE).mse_optimizer(TRUE, k, S_0, R, t, call)


